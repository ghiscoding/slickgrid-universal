<h4>Quick intro</h4>
<p>
  One of the best JavaScript datagrids
  <a href="https://github.com/mleibman/SlickGrid" target="_blank" rel="noreferrer">SlickGrid</a> which was originally developed by @mleibman is
  now available to Svelte. I have tried, and used, a few datagrids and SlickGrid beats most of them in terms of functionalities and performance
  (it can easily handle a million rows).
</p>
